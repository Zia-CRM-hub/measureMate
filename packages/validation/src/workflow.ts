export const ORDER_STATUSES = [
  'DRAFT', 'CONFIRMED', 'MEASUREMENT_PENDING', 'MEASUREMENT_COMPLETED', 'CUTTING', 'STITCHING', 'TRIAL_READY',
  'TRIAL_COMPLETED', 'ALTERATION', 'FINISHING', 'QUALITY_CHECK', 'READY_FOR_DELIVERY', 'PARTIALLY_DELIVERED',
  'DELIVERED', 'CLOSED', 'CANCELLED',
] as const;
export type OrderStatus = (typeof ORDER_STATUSES)[number];

/** System states that tenants cannot rename/remove (financial and historical consistency). */
export const PROTECTED_STATUSES: OrderStatus[] = ['DRAFT', 'CONFIRMED', 'DELIVERED', 'CLOSED', 'CANCELLED'];
export const TERMINAL_STATUSES: OrderStatus[] = ['CLOSED', 'CANCELLED'];

const PRODUCTION: OrderStatus[] = [
  'MEASUREMENT_PENDING', 'MEASUREMENT_COMPLETED', 'CUTTING', 'STITCHING', 'TRIAL_READY', 'TRIAL_COMPLETED',
  'ALTERATION', 'FINISHING', 'QUALITY_CHECK', 'READY_FOR_DELIVERY',
];

/**
 * Allowed transitions. Production stages move forward or step back for rework (real shops loop through
 * trial and alteration). CLOSED and CANCELLED are terminal.
 */
export const TRANSITIONS: Record<OrderStatus, OrderStatus[]> = {
  DRAFT: ['CONFIRMED', 'CANCELLED'],
  CONFIRMED: [...PRODUCTION, 'CANCELLED'],
  MEASUREMENT_PENDING: ['MEASUREMENT_COMPLETED', 'CANCELLED'],
  MEASUREMENT_COMPLETED: ['CUTTING', 'MEASUREMENT_PENDING', 'CANCELLED'],
  CUTTING: ['STITCHING', 'MEASUREMENT_COMPLETED', 'CANCELLED'],
  STITCHING: ['TRIAL_READY', 'FINISHING', 'CUTTING', 'CANCELLED'],
  TRIAL_READY: ['TRIAL_COMPLETED', 'STITCHING', 'CANCELLED'],
  TRIAL_COMPLETED: ['ALTERATION', 'FINISHING', 'TRIAL_READY', 'CANCELLED'],
  ALTERATION: ['TRIAL_READY', 'FINISHING', 'CANCELLED'],
  FINISHING: ['QUALITY_CHECK', 'ALTERATION', 'CANCELLED'],
  QUALITY_CHECK: ['READY_FOR_DELIVERY', 'ALTERATION', 'FINISHING', 'CANCELLED'],
  READY_FOR_DELIVERY: ['PARTIALLY_DELIVERED', 'DELIVERED', 'QUALITY_CHECK', 'CANCELLED'],
  PARTIALLY_DELIVERED: ['DELIVERED', 'CANCELLED'],
  DELIVERED: ['CLOSED'],
  CLOSED: [],
  CANCELLED: [],
};

export function canTransition(from: OrderStatus, to: OrderStatus): boolean {
  return TRANSITIONS[from].includes(to);
}
